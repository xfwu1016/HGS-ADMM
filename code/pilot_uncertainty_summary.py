"""Summarize the existing 100-step pilot envelopes without refitting models.

Each of 45 runs contributes one data-edge uncertainty/center sum ratio and
one mean total-variation distance across its data-factor allocation stars.
Model summaries are medians over 15 runs (5 samples x 3 reused layouts).
These runs are not 15 independent datasets. Structural factors are excluded.
"""
from pathlib import Path
import csv
import json
import hashlib
import numpy as np
ROOT=Path(__file__).resolve().parents[1]

def main():
    source=ROOT/'results/pilot_budget_weights.json'
    records=json.loads(source.read_text())
    rows=[]
    for rec in records:
        if not rec['key'].startswith('synthetic_'):
            continue
        model=rec['key'].split('_')[1]
        stars=[s for s in rec['stars'] if s['kind'] in ('squared','huber','logistic')]
        if not stars:
            raise ValueError('No data stars in '+rec['key'])
        uncertainty=np.concatenate([np.array(s['operator_norm'])*rec['radius'] for s in stars])
        center=np.concatenate([np.array(s['prediction_norm']) for s in stars])
        upper=np.concatenate([np.array(s['c_upper']) for s in stars])
        lower=np.concatenate([np.array(s['c_lower']) for s in stars])
        if not np.allclose(upper,center+uncertainty,rtol=1e-12,atol=1e-12):
            raise ValueError('Stored upper envelope differs from its definition')
        if not np.allclose(lower,np.maximum(0,center-uncertainty),rtol=1e-12,atol=1e-12):
            raise ValueError('Stored lower envelope differs from its definition')
        if center.sum()<=0:
            raise ValueError('Zero total center; a finite ratio is not defined')
        distances=[]
        for star in stars:
            w=np.array(star['omega']);d=star['degree']
            if len(w)!=d or not np.isclose(w.sum(),1,rtol=0,atol=1e-12) or np.any(w<=0):
                raise ValueError('Invalid allocation')
            distances.append(float(.5*np.abs(w-1/d).sum()))
        rows.append(dict(key=rec['key'],model=model,data_edges=len(center),
                         uncertainty_center_ratio=float(uncertainty.sum()/center.sum()),
                         mean_star_tv=float(np.mean(distances)),
                         zero_lower_edges=int(np.count_nonzero(lower==0))))
    if len(rows)!=45 or len({r['key'] for r in rows})!=45:
        raise ValueError('Expected 45 distinct simulated pilot configurations')
    results=ROOT/'results';tables=ROOT/'tables';tables.mkdir(exist_ok=True)
    with (results/'pilot_uncertainty_diagnostics.csv').open('w',newline='') as f:
        w=csv.DictWriter(f,fieldnames=list(rows[0]));w.writeheader();w.writerows(rows)
    summaries=[]
    for model,label in [('fused','Squared fused'),('huber','Huber'),('logistic','Logistic')]:
        rr=[r for r in rows if r['model']==model];assert len(rr)==15
        summaries.append(dict(model=model,label=label,runs=len(rr),
            median_uncertainty_center_ratio=float(np.median([r['uncertainty_center_ratio'] for r in rr])),
            median_mean_star_tv=float(np.median([r['mean_star_tv'] for r in rr])),
            zero_lower_edges=sum(r['zero_lower_edges'] for r in rr),
            data_edges=sum(r['data_edges'] for r in rr)))
    payload=dict(source=source.name,source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
                 scope='data factors only; 5 samples per model reused on 3 layouts',
                 uncertainty_ratio='sum_edges(operator_norm * radius) / sum_edges(prediction_norm)',
                 allocation_distance='mean_stars(0.5 * sum_edges(abs(omega - 1/degree)))',
                 summaries=summaries)
    (results/'pilot_uncertainty_summary.json').write_text(json.dumps(payload,indent=2)+'\n')
    body='\n'.join(f"{r['label']} & {r['median_uncertainty_center_ratio']:.2f} & {r['median_mean_star_tv']:.3f} & {r['zero_lower_edges']}/{r['data_edges']} \\\\" for r in summaries)
    table=r'''% Generated by code/pilot_uncertainty_summary.py; no new optimization fits.
\begin{table}[H]\centering\small
\caption{Data-factor uncertainty and allocations after 100 pilot steps.}
\label{tab:pilot-uncertainty}
\begin{tabular}{@{}lrrr@{}}\toprule
Model & Uncertainty/center & Distance from uniform & Zero lower bounds\\
\midrule
'''+body+r'''
\bottomrule\end{tabular}
\par\smallskip
\begin{minipage}{\linewidth}\footnotesize
For each run, uncertainty/center is the sum of $\|A_{aj}\|_{\rm op}R$
divided by the sum of $\|A_{aj}\widetilde\beta_j\|$ over data edges,
with $R=\sqrt{2G/\mu}$. The allocation distance is the mean, over data
factors, of $\frac12\sum_j|\omega_{aj}-1/d_a|$, where $d_a$ is the factor degree.
The two columns report medians over 15 configurations per model: five samples
reused on three layouts. The last column counts zero lower norm bounds
among all data edges in those configurations. Structural factors are excluded.
\end{minipage}
\end{table}
'''
    (tables/'pilot_uncertainty_table.tex').write_text(table)
    r=[x['median_uncertainty_center_ratio'] for x in summaries]
    d=[x['median_mean_star_tv'] for x in summaries]
    text=(r'''The stored pilot envelopes explain part of this limited gain
(Supplementary Table~\ref{supp-tab:pilot-uncertainty}). For data edges, the
ratio of the summed uncertainty terms $\|A_{aj}\|_{\rm op}\sqrt{2G/\mu}$
to the summed pilot prediction norms had model-wise medians of '''
+f'{r[0]:.2f}, {r[1]:.2f} and {r[2]:.2f}'
+r''' for fused, Huber and logistic regression.
Every data-edge lower norm bound was zero. The median allocation distances
from uniform were '''+f'{d[0]:.3f}, {d[1]:.3f} and {d[2]:.3f}'
+r''', respectively, using the mean star-wise total-variation distance in the
supplement. Thus these pilots produced conservative envelopes and only modest
changes in shares. This diagnoses the tested finite-pilot rule; it does not
establish that accurately known oracle shares or other weight-selection rules
would have the same performance.
''')
    (tables/'pilot_uncertainty_text.tex').write_text(text)
    print(json.dumps(payload,indent=2))
if __name__=='__main__':main()
