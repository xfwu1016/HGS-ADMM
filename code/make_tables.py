"""Generate every empirical LaTeX table directly from the final CSV files.

Numeric summaries are rounded to three significant figures. Iteration
variability is the sample standard deviation across five fixed simulation
seeds. Traffic counts optimization payload, excluding offline diagnostics.
"""
from pathlib import Path
import csv,math
import numpy as np

ROOT=Path(__file__).resolve().parents[1]
RESULTS=ROOT/'results';TABLES=ROOT/'tables'
MODELS=[('squared','Squared fused'),('huber','Huber'),('logistic','Logistic')]


def read(name):
    with (RESULTS/name).open() as f:return list(csv.DictReader(f))


def sig(value):
    """Three significant figures, retaining useful decimal zeros."""
    x=float(value)
    if not np.isfinite(x):return '--'
    if x==0:return '0'
    exponent=math.floor(math.log10(abs(x)))
    if exponent < -3:
        mantissa=x/(10**exponent)
        return rf'\({mantissa:.2f}\times10^{{{exponent}}}\)'
    decimals=max(0,2-exponent)
    rounded=round(x,2-exponent)
    return f'{rounded:,.{decimals}f}' if abs(rounded)>=1000 else f'{rounded:.{decimals}f}'


def count(value):
    x=float(value)
    assert x==int(x)
    return f'{int(x):,}'


def ms(rows,column,scale=1):
    x=np.array([float(r[column])/scale for r in rows])
    assert len(x)==5
    return f'{sig(x.mean())} ({sig(x.std(ddof=1))})'


def mean(rows,column,scale=1):
    return sig(np.mean([float(r[column])/scale for r in rows]))


def exactly_one(rows):
    assert len(rows)==1,len(rows)
    return rows[0]


def table(caption,label,columns,header,body,small=True,placement='tbp'):
    # Appendix E tables retain native 8-point type in the two-column text flow.
    appendix_labels = {'tab:full-synthetic', 'tab:sparse',
                       'tab:rho', 'tab:constant-diagnostics'}
    environment = 'table' if label == 'tab:analytic' or label in appendix_labels else 'table*'
    placement = 'H' if label in appendix_labels else ('t' if placement == 'H' else placement)
    return '\n'.join([
        '% Generated by code/make_tables.py from final CSVs; do not edit numeric entries.',
        (rf'\begin{{{environment}}}[pos={placement},abovecap=4pt]' if label in appendix_labels
         else rf'\begin{{{environment}}}[pos={placement}]'),r'\centering',r'\small' if small else r'\footnotesize',
        (r'\setlength{\tabcolsep}{2.5pt}' if label in {'tab:full-synthetic', 'tab:constant-diagnostics'} else (r'\setlength{\tabcolsep}{2.8pt}' if label in {'tab:sparse', 'tab:rho'} else r'\setlength{\tabcolsep}{3.5pt}')),(r'\renewcommand{\arraystretch}{1.0}' if label in appendix_labels else r'\renewcommand{\arraystretch}{1.06}'),
        rf'\caption{{{caption}}}',rf'\label{{{label}}}',rf'\begin{{tabular}}{{{columns}}}',
        r'\toprule',header,r'\midrule',*body,r'\bottomrule',r'\end{tabular}',rf'\end{{{environment}}}',''])


def main():
    TABLES.mkdir(exist_ok=True)
    runs=read('runs.csv');cp=read('consensus_baseline.csv')
    stopping=read('stopping_certificates.csv');rho=read('penalty_sensitivity.csv')
    assert len(runs)==138 and len(cp)==30 and len(rho)==27
    assert all(r['converged']=='True' for r in runs+cp)
    synthetic=[r for r in runs if r['kind']=='synthetic' and r['zero_edges']=='0']
    def group(loss,M,N,metric):
        rows=[r for r in synthetic if r['loss']==loss and int(r['row_parts'])==M
              and int(r['column_parts'])==N and r['metric']==metric]
        assert len(rows)==5
        return rows
    body=[]
    for loss,name in MODELS:
        for M in (4,8):
            u=group(loss,M,4,'unit');b=group(loss,M,4,'budget')
            body.append(f'{name} & ${M}\\times4$ & {ms(u,"iterations")} & {ms(b,"iterations")} & '
                        f'{mean(u,"communicated_scalars",1e6)} & {mean(b,"communicated_scalars",1e6)} \\\\')
    header=(r'& & \multicolumn{2}{c}{Iterations} & \multicolumn{2}{c}{Traffic ($10^6$ scalars)}\\'+'\n'+
            r'\cmidrule(lr){3-4}\cmidrule(lr){5-6}'+'\n'+
            r'Model & Layout & Unit & Budget & Unit & Budget\\')
    text=table(r'Hybrid graph-splitting comparisons at $\rho=1$. Iterations are means (sample standard deviations) over five seeds; traffic is the mean optimization payload. Both metrics use the same indicated data layout and a relative Fenchel gap of $10^{-6}$. Values are rounded to three significant figures.',
               'tab:hybrid','llrrrr',header,body)
    (TABLES/'hybrid_comparison.tex').write_text(text)

    body=[]
    for loss,name in MODELS:
        for M in (4,8):
            c=[r for r in cp if r['loss']==loss and int(r['row_parts'])==M]
            b=group(loss,M,4,'budget')
            body.append(f'{name} & {M} & {ms(c,"iterations")} & {ms(b,"iterations")} & '
                        f'{mean(c,"communicated_scalars",1e6)} & {mean(b,"communicated_scalars",1e6)} \\\\')
    header=(r'& & \multicolumn{2}{c}{Iterations} & \multicolumn{2}{c}{Traffic ($10^6$ scalars)}\\'+'\n'+
            r'\cmidrule(lr){3-4}\cmidrule(lr){5-6}'+'\n'+
            r'Model & $M$ & Consensus & Graph budget & Consensus & Graph budget\\')
    text=table(r'Sample-consensus comparator and budget-weighted graph splitting at $\rho=1$ and relative gap $10^{-6}$. Iterations are means (sample standard deviations) over five seeds; traffic is the mean payload. Local data storage differs: each consensus worker holds all features for its sample block, whereas graph splitting uses $M\times4$ data blocks.',
               'tab:consensus','lrrrrr',header,body)
    (TABLES/'consensus_comparison.tex').write_text(text)

    body=[]
    for case,name in [('real_diabetes','Diabetes'),('real_breast_cancer','Breast cancer')]:
        for M in (4,8):
            u=exactly_one([r for r in runs if r['case']==case and int(r['row_parts'])==M and r['column_parts']=='4' and r['metric']=='unit'])
            b=exactly_one([r for r in runs if r['case']==case and int(r['row_parts'])==M and r['column_parts']=='4' and r['metric']=='budget'])
            body.append(f'{name} & ${M}\\times4$ & {count(u["iterations"])} & {count(b["iterations"])} & '
                        f'{sig(float(u["communicated_scalars"])/1e6)} & {sig(float(b["communicated_scalars"])/1e6)} \\\\')
    text=table(r'Public-data examples with a fixed training, validation and test split. All rows use $\rho=1$ and a relative Fenchel gap of $10^{-7}$. Traffic counts optimization payload only. The two metrics estimate the same selected statistical model on each dataset.',
               'tab:real','llrrrr',header.replace(r'Model & $M$ & Consensus & Graph budget & Consensus & Graph budget',r'Example & Layout & Unit & Budget & Unit & Budget'),body)
    (TABLES/'real_results.tex').write_text(text)

    body=[]
    for case,name,metric in [('real_diabetes','Diabetes','test_rmse'),('real_breast_cancer','Breast cancer','test_logloss')]:
        for threshold in (1e-3,1e-5,1e-7):
            s=exactly_one([r for r in stopping if r['key']==case+'_M4_N4_unit' and float(r['threshold'])==threshold])
            threshold_tex=rf'$10^{{{round(math.log10(threshold))}}}$'
            dist=math.sqrt(float(s['squared_distance_reference']));bound=math.sqrt(float(s['strong_convexity_bound']))
            score=f'{float(s[metric]):.3f}' if metric=='test_rmse' else f'{float(s[metric]):.5f}'
            body.append(f'{name} & {threshold_tex} & {count(s["iteration"])} & {score} & {sig(dist)} & {sig(bound)} \\\\')
    header=r'Example & $\epsilon$ & Iterations & Test score & $\|\beta-\beta_{\rm ref}\|$ & $\sqrt{2G/\mu}$\\'
    text=table(r'Certified stopping on the $4\times4$ layout with unit weights. Each row is the first diagnostic check attaining a relative gap at most $\epsilon$. The test score is root mean squared error in original response units for diabetes and log loss for breast cancer. The radius uses the actual absolute gap $G$ and bounds distance to the exact minimizer; distance to a numerical reference with relative gap at most $10^{-10}$ is an empirical diagnostic.',
               'tab:stopping','llrrrr',header,body,small=False)
    (TABLES/'stopping_results.tex').write_text(text)

    additional=[];body=[]
    for loss,name in MODELS:
        body.append(r'\multicolumn{5}{l}{\itshape '+name+r'}\\')
        for M,N in [(1,1),(4,1),(4,4),(8,4)]:
            for metric in ('unit','budget'):
                g=group(loss,M,N,metric)
                body.append(f'${M}\\times{N}$ & {metric.capitalize()} & '
                            f'{ms(g,"iterations")} & {mean(g,"communicated_scalars",1e6)} & {ms(g,"elapsed_seconds")} \\\\')
    header=r'Layout & Metric & Iterations & Traffic ($10^6$) & Time (s)\\'
    text=table(r'Complete synthetic results ($\rho=1$; relative gap $10^{-6}$): five-seed means with sample standard deviations for iterations and time. Traffic and timing follow Section~\ref{sec:protocol}.',
               'tab:full-synthetic','llrrr',header,body,small=False,placement='H')
    additional.append(text)

    body=[]
    for padded,name in [('0','Sparse'),('1','Padded')]:
        for metric in ('unit','budget'):
            s=exactly_one([r for r in runs if r['case']=='synthetic_fused_0' and r['row_parts']=='4'
                           and r['column_parts']=='4' and r['zero_edges']==padded and r['metric']==metric])
            body.append(f'{name} & {metric.capitalize()} & {count(s["edges"])} & {count(s["iterations"])} & '
                        f'{sig(float(s["communication_per_iteration"])/1e3)} & '
                        f'{sig(float(s["communicated_scalars"])/1e6)} & '
                        f'{sig(float(s["factorization_storage_scalars"])/1e3)} \\\\')
    header=(r'& & & & \multicolumn{2}{c}{Traffic} & Storage\\'+'\n'+
            r'\cmidrule(lr){5-6}'+'\n'+r'Graph & Metric & Edges & Iter. & \makecell{Round\\($10^3$)} & \makecell{Total\\($10^6$)} & ($10^3$)\\')
    text=table(r'Zero-block padding in fused regression (seed 0, $4\times4$; relative gap $10^{-6}$) preserves the objective. Traffic and cached dense Cholesky storage count scalars.',
               'tab:sparse','llrrrrr',header,body,small=False,placement='H')
    additional.append(text)

    body=[]
    for loss,name in MODELS:
        for method,metric,method_name in [('graph','unit','Graph unit'),('graph','budget','Graph budget'),('sample_consensus','none','Consensus')]:
            values=[]
            for penalty in (.1,1.,10.):
                s=exactly_one([r for r in rho if r['loss']==loss and r['method']==method and r['metric']==metric and float(r['rho'])==penalty])
                value=count(s['iterations'])
                if s['converged']!='True':value+=r'$^{\dagger}$'
                values.append(value)
            body.append(f'{name} & {method_name} & '+' & '.join(values)+r'\\')
    capped=sum(r['converged']!='True' for r in rho)
    cap_text=(r' All runs reached the requested gap.' if capped==0 else
              r' A dagger marks an iteration-capped run; its final gap is retained in the accompanying CSV.')
    text=table(r'Iteration counts for penalty sensitivity (seed 0, $8\times4$; consensus $M=8$), with relative gap $10^{-6}$ and a 50,000-iteration cap.'+cap_text,
               'tab:rho','llrrr',r'Model & Method & $\rho=0.1$ & $\rho=1$ & $\rho=10$\\',body,small=False,placement='H')
    additional.append(text)

    body=[]
    for loss,name in MODELS:
        for M in (4,8):
            u=group(loss,M,4,'unit');b=group(loss,M,4,'budget')
            body.append(f'{name} & ${M}\\times4$ & {mean(u,"distance_constant_approx")} & '
                        f'{mean(b,"distance_constant_approx")} & {mean(b,"prediction_dispersion_H")} & '
                        f'{mean(b,"gradient_dispersion_G")} \\\\')
    text=table(r'Approximate zero-start constants and disagreement terms (five-seed means), using a numerical KKT reference. Prediction and gradient terms use uniform incidence budgets.',
               'tab:constant-diagnostics','llrrrr',r'Model & Layout & \makecell{Unit\\constant} & \makecell{Budget\\constant} & \makecell{Prediction\\term} & \makecell{Gradient\\term}\\',body,small=False,placement='H')
    additional.append(text)
    (TABLES/'additional_results.tex').write_text(
        r'\begingroup\setlength{\intextsep}{5pt}' + '\n'
        + '\n'.join(additional) + r'\endgroup' + '\n')

    analytic=read('analytic_partition.csv');body=[]
    for M in sorted(set(int(r['rows']) for r in analytic)):
        u=exactly_one([r for r in analytic if int(r['rows'])==M and r['metric']=='unit'])
        b=exactly_one([r for r in analytic if int(r['rows'])==M and r['metric']=='budget'])
        body.append(f'{M} & {sig(u["C0"])} & {sig(b["C0"])} & {count(u["iterations"])} & {count(b["iterations"])} \\\\')
    text=table(r'Exact ridge example with $\mu=0.2$ and $\rho=1$. Constants use the analytic primal and dual optimum and are displayed to three significant figures; iteration counts are exact. The absolute gap $10^{-10}$ is checked at every iteration.',
               'tab:analytic','rrrrr',r'$M$ & $C_{\rm E}$ & $C_{\rm B}$ & Unit iterations & Budget iterations\\',body,placement='H')
    (TABLES/'analytic_results.tex').write_text(text)
    print('Generated '+', '.join(p.name for p in sorted(TABLES.glob('*.tex'))))


if __name__=='__main__':main()
