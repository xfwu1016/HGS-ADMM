"""Generate every empirical LaTeX table directly from the final CSV files.

Iteration means are rounded to the nearest integer. Standard deviations
and time summaries retain three significant figures. Iteration
variability is the sample standard deviation across five fixed simulation
seeds. Traffic counts optimization payload, excluding offline diagnostics.
"""
from pathlib import Path
import csv,math
from collections import defaultdict
import numpy as np

from table_values import iteration_mean, sig

ROOT=Path(__file__).resolve().parents[1]
RESULTS=ROOT/'results';TABLES=ROOT/'tables'
MODELS=[('squared','Squared fused'),('huber','Huber'),('logistic','Logistic')]


def read(name):
    with (RESULTS/name).open() as f:return list(csv.DictReader(f))


def count(value):
    x=float(value)
    assert x==int(x)
    return f'{int(x):,}'


def ms(rows,column,scale=1):
    x=np.array([float(r[column])/scale for r in rows])
    assert len(x)==5
    display_mean = iteration_mean if column == 'iterations' else sig
    return rf'\tablems{{{display_mean(x.mean())}}}{{{sig(x.std(ddof=1))}}}'


def mean(rows,column,scale=1):
    return sig(np.mean([float(r[column])/scale for r in rows]))


def exactly_one(rows):
    assert len(rows)==1,len(rows)
    return rows[0]


def table(caption,label,columns,header,body,small=True,placement='tbp',notes=''):
    """Render native-size booktabs tables; main comparisons span the text width.

    Means and SDs align independently in local boxes.  Numeric data columns
    retain their CSV-derived values; decimal columns use the CAS dcolumn package.
    """
    appendix_labels = {'tab:full-synthetic', 'tab:sparse',
                       'tab:rho', 'tab:constant-diagnostics'}
    appendix = label in appendix_labels
    wide = label not in appendix_labels | {'tab:analytic', 'tab:continuation'}
    environment = 'table*' if wide else 'table'
    placement = 'H' if appendix else ('t' if placement == 'H' else placement)
    width = r'\textwidth' if wide else r'\linewidth'
    begin_tabular = (rf'\begin{{tabular*}}{{{width}}}{{@{{\extracolsep{{\fill}}}}{columns}@{{}}}}'
                     if wide or label == 'tab:analytic' else rf'\begin{{tabular}}{{@{{}}{columns}@{{}}}}')
    end_tabular = r'\end{tabular*}' if wide or label == 'tab:analytic' else r'\end{tabular}'
    lines = [
        '% Generated by code/make_tables.py from final CSVs; do not edit numeric entries.',
        (rf'\begin{{{environment}}}[pos={placement},abovecap=4pt]' if appendix
         else rf'\begin{{{environment}}}[pos={placement}]'),
        r'\centering', r'\small' if small else r'\footnotesize',
        (r'\setlength{\tabcolsep}{2.5pt}' if appendix else r'\setlength{\tabcolsep}{5pt}'),
        (r'\renewcommand{\arraystretch}{1.04}' if appendix else r'\renewcommand{\arraystretch}{1.12}'),
        # Each float scopes this definition; no manuscript-level macros are needed.
        (r'\newcommand{\tablems}[2]{\makebox[3.0em][r]{#1}\,\makebox[3.8em][l]{(#2)}}' if appendix
         else r'\newcommand{\tablems}[2]{\makebox[2.9em][r]{#1}\,\makebox[2.75em][l]{(#2)}}'),
        rf'\caption{{{caption}}}',rf'\label{{{label}}}',begin_tabular,
        r'\toprule',header,r'\midrule',*body,r'\bottomrule',end_tabular]
    if notes:
        lines += [r'\par\vspace{3pt}',rf'\begin{{minipage}}{{{width}}}',
                  r'\footnotesize\raggedright '+notes,r'\end{minipage}']
    return '\n'.join([*lines,rf'\end{{{environment}}}',''])


def write_main_table(name, rows, rounding_note=''):
    TABLES.mkdir(exist_ok=True)
    path = ROOT / 'code' / 'table_templates' / f'{name}.tex.in'
    template = path.read_text()
    if template.count('@@ROWS@@') != 1:
        raise ValueError(f'Missing or ambiguous table body in {path}')
    table_text = template.replace('@@ROWS@@', '\n'.join(rows))
    (TABLES / f'{name}.tex').write_text(table_text.replace('@@ROUNDING@@', rounding_note))


def write_pilot_table(summary):
    rows = []
    for loss, name in MODELS:
        if rows:
            rows.append(r'\addlinespace[3pt]')
        for i, (m, j) in enumerate(((2, 8), (4, 4), (8, 2))):
            group = [exactly_one([r for r in summary if r['loss'] == loss
                                 and int(r['row_parts']) == m and int(r['column_parts']) == j
                                 and r['metric'] == metric]) for metric in ('unit', 'budget', 'pilot')]
            its = [r'\tablems{' + iteration_mean(r['total_iterations_mean']) + '}{' +
                   sig(r['total_iterations_sd']) + '}' for r in group]
            traffic = [sig(float(r['total_optimization_allocation_payload_mean']) / 1e6) for r in group]
            layout = '$' + str(m) + r'\times' + str(j) + '$'
            rows.append(' & '.join([name if i == 0 else '', layout, *its, *traffic]) + r'\\')
    write_main_table('pilot_budget_results', rows)


def write_continuation_table():
    paired = defaultdict(dict)
    for filename in ('pilot_continuation_runs.csv', 'pilot_continuation_public.csv'):
        for record in read(filename):
            key = tuple(record[k] for k in ('data', 'model', 'seed', 'row_parts', 'column_parts'))
            if record['method'] in paired[key]:
                raise ValueError(f'Duplicate {record["method"]} for {key}')
            paired[key][record['method']] = int(record['payload_with_certificate_bound'])
    for record in read('matched_output_control.csv'):
        key = tuple(record[k] for k in ('data', 'model', 'seed', 'sample_blocks', 'feature_blocks'))
        if key not in paired or 'switch_uniform' in paired[key]:
            raise ValueError(f'Unexpected matched case {key}')
        if paired[key]['unit_continue'] != int(record['learned_scalars']):
            raise ValueError(f'Pilot continuation payload differs between runs for {key}')
        paired[key]['switch_uniform'] = int(record['uniform_scalars'])
    for case in paired.values():
        case['better_fixed'] = min(case['unit'], case['budget'])
    comparisons = [('Restart', 'unit_restart'), ('Switch to uniform', 'switch_uniform'),
                   ('Fixed unit', 'unit'), ('Fixed uniform budget', 'budget'),
                   ('Lower-cost fixed metric', 'better_fixed')]
    rows = []
    rounding_note = ''
    for label, ref in comparisons:
        cells = [label]
        for kind, expected in [('synthetic', 45), ('real', 4)]:
            cases = [case for key, case in paired.items() if key[0] == kind]
            if len(cases) != expected:
                raise ValueError(f'Expected {expected} paired {kind} cases')
            changes = [100 * (case['unit_continue'] / case[ref] - 1) for case in cases]
            median = float(np.median(changes))
            display = '$' + f'{median:+.1f}' + r'\%$'
            if ref == 'switch_uniform' and kind == 'synthetic' and 0 < abs(median) < 0.05:
                display = r'$\approx 0\%$'
                rounding_note = 'Its simulated median is $' + f'{median:+.5f}' + r'\%$.'
            cells.extend([f'{sum(x < 0 for x in changes)}/{len(cases)}', display])
        rows.append(' & '.join(cells) + r'\\')
    write_main_table('continuation_results', rows, rounding_note)


def main():
    TABLES.mkdir(exist_ok=True)
    runs=read('runs.csv');cp=read('consensus_baseline.csv')
    stopping=read('stopping_certificates.csv');rho=read('penalty_sensitivity.csv')
    assert len(runs)==138 and len(cp)==30 and len(rho)==27
    assert all(r['converged']=='True' for r in runs+cp)
    synthetic=[r for r in runs if r['kind']=='synthetic' and r['zero_edges']=='0']
    def group(loss,M,N,metric):
        rows=[r for r in synthetic if r['loss']==loss and int(r['row_parts'])==M
              and int(r['column_parts'])==N and r['metric']==metric]
        assert len(rows)==5
        return rows
    body=[]
    for loss,name in MODELS:
        if body:body.append(r'\addlinespace[3pt]')
        for M in (4,8):
            u=group(loss,M,4,'unit');b=group(loss,M,4,'budget')
            body.append(f'{name if M == 4 else ""} & ${M}\\times4$ & {ms(u,"iterations")} & {ms(b,"iterations")} & '
                        f'{mean(u,"communicated_scalars",1e6)} & {mean(b,"communicated_scalars",1e6)} \\\\')
    write_main_table('hybrid_comparison', body)

    body=[]
    for loss,name in MODELS:
        if body:body.append(r'\addlinespace[3pt]')
        body.append(r'\multicolumn{5}{@{}l}{\itshape '+name+r'}\\')
        for M in (4,8):
            c=[r for r in cp if r['loss']==loss and int(r['row_parts'])==M]
            b=group(loss,M,4,'budget')
            body.append(f'{M} & {ms(c,"iterations")} & {ms(b,"iterations")} & '
                        f'{mean(c,"communicated_scalars",1e6)} & {mean(b,"communicated_scalars",1e6)} \\\\')
    write_main_table('consensus_comparison', body)

    body=[]
    for case,name in [('real_diabetes','Diabetes'),('real_breast_cancer','Breast cancer')]:
        if body:body.append(r'\addlinespace[3pt]')
        for M,J in ((1,1),(4,1),(4,4),(8,4)):
            layout=[r for r in runs if r['case']==case and int(r['row_parts'])==M and int(r['column_parts'])==J]
            u=exactly_one([r for r in layout if r['metric']=='unit'])
            b=exactly_one([r for r in layout if r['metric']=='budget'])
            body.append(f'{name if M == 1 else ""} & ${M}\\times{J}$ & {count(u["iterations"])} & {count(b["iterations"])} & '
                        f'{sig(float(u["communicated_scalars"])/1e6)} & {sig(float(b["communicated_scalars"])/1e6)} \\\\')
    write_main_table('real_results', body)

    body=[]
    for case,name,metric in [('real_diabetes','Diabetes','test_rmse'),('real_breast_cancer','Breast cancer','test_logloss')]:
        if body:body.append(r'\addlinespace[3pt]')
        score_name='RMSE' if metric=='test_rmse' else 'log loss'
        body.append(r'\multicolumn{5}{@{}l}{\itshape '+name+' (test '+score_name+r')}\\')
        for threshold in (1e-3,1e-5,1e-7):
            s=exactly_one([r for r in stopping if r['key']==case+'_M4_N4_unit' and float(r['threshold'])==threshold])
            threshold_tex=rf'$10^{{{round(math.log10(threshold))}}}$'
            dist=math.sqrt(float(s['squared_distance_reference']));bound=math.sqrt(float(s['strong_convexity_bound']))
            score=f'{float(s[metric]):.3f}' if metric=='test_rmse' else f'{float(s[metric]):.5f}'
            body.append(f'{threshold_tex} & {count(s["iteration"])} & {score} & {sig(dist)} & {sig(bound)} \\\\')
    write_main_table('stopping_results', body)

    additional=[];body=[]
    for loss,name in MODELS:
        if body:body.append(r'\addlinespace[3pt]')
        body.append(r'\multicolumn{5}{l}{\itshape '+name+r'}\\')
        for M,N in [(1,1),(4,1),(4,4),(8,4)]:
            for metric in ('unit','budget'):
                g=group(loss,M,N,metric)
                body.append(f'${M}\\times{N}$ & {metric.capitalize()} & '
                            f'{ms(g,"iterations")} & {mean(g,"communicated_scalars",1e6)} & {ms(g,"elapsed_seconds")} \\\\')
    header=r'Layout & Metric & Iterations & Update scalars ($10^6$) & Time (s)\\'
    text=table(r'Synthetic results at relative gap $10^{-6}$ using projected anchor multipliers. Iterations and sequential times are five-sample means (sample SD). Iteration means are rounded to the nearest integer. Percentage changes use unrounded means. Update traffic excludes gap checks.',
               'tab:full-synthetic','llrrr',header,body,small=False,placement='H')
    additional.append(text)

    body=[]
    for padded,name in [('0','Sparse'),('1','Padded')]:
        for metric in ('unit','budget'):
            s=exactly_one([r for r in runs if r['case']=='synthetic_fused_0' and r['row_parts']=='4'
                           and r['column_parts']=='4' and r['zero_edges']==padded and r['metric']==metric])
            body.append(f'{name} & {metric.capitalize()} & {count(s["edges"])} & {count(s["iterations"])} & '
                        f'{sig(float(s["communication_per_iteration"])/1e3)} & '
                        f'{sig(float(s["communicated_scalars"])/1e6)} & '
                        f'{sig(float(s["factorization_storage_scalars"])/1e3)} \\\\')
    header=(r'& & & & \multicolumn{2}{c}{Traffic} & Storage\\'+'\n'+
            r'\cmidrule(lr){5-6}'+'\n'+r'Graph & Metric & Edges & Iter. & \makecell{Round\\($10^3$)} & \makecell{Total\\($10^6$)} & ($10^3$)\\')
    text=table(r'Zero-block padding in fused regression (seed 0, $4\times4$). Projected anchor multipliers certify a relative gap of $10^{-6}$. Traffic and cached Cholesky storage count scalars.',
               'tab:sparse','llrrrrr',header,body,small=False,placement='H')
    additional.append(text)

    body=[]
    for loss,name in MODELS:
        if body:body.append(r'\addlinespace[3pt]')
        for method,metric,method_name in [('graph','unit','Graph unit'),('graph','budget','Graph budget'),('sample_consensus','none','Consensus')]:
            values=[]
            for penalty in (.1,1.,10.):
                s=exactly_one([r for r in rho if r['loss']==loss and r['method']==method and r['metric']==metric and float(r['rho'])==penalty])
                value=count(s['iterations'])
                if s['converged']!='True':value+=r'$^{\dagger}$'
                values.append(value)
            body.append(f'{name if method_name == "Graph unit" else ""} & {method_name} & '+' & '.join(values)+r'\\')
    capped=sum(r['converged']!='True' for r in rho)
    cap_text=(r' All runs reached the requested gap.' if capped==0 else
              r' A dagger marks an iteration-capped run; its final gap is retained in the accompanying CSV.')
    text=table(r'Penalty sensitivity for seed 0 on $8\times4$ (consensus $M=8$). At relative gap $10^{-6}$, graph runs use projected anchor multipliers and consensus uses projected prediction and, where applicable, fusion multipliers.'+cap_text,
               'tab:rho','llrrr',r'Model & Method & $\rho=0.1$ & $\rho=1$ & $\rho=10$\\',body,small=False,placement='H')
    additional.append(text)

    body=[]
    for loss,name in MODELS:
        if body:body.append(r'\addlinespace[3pt]')
        for M in (4,8):
            u=group(loss,M,4,'unit');b=group(loss,M,4,'budget')
            body.append(f'{name if M == 4 else ""} & ${M}\\times4$ & {mean(u,"distance_constant_approx")} & '
                        f'{mean(b,"distance_constant_approx")} & {mean(b,"prediction_dispersion_H")} & '
                        f'{mean(b,"gradient_dispersion_G")} \\\\')
    text=table(r'Approximate zero-start constants and disagreement terms (five-sample means) at a reference fit certified to relative gap $10^{-10}$ with projected anchor multipliers. Prediction and gradient terms use uniform incidence budgets.',
               'tab:constant-diagnostics','llrrrr',r'Model & Layout & \makecell{Unit\\constant} & \makecell{Budget\\constant} & \makecell{Prediction\\term} & \makecell{Gradient\\term}\\',body,small=False,placement='H')
    additional.append(text)
    (TABLES/'full_synthetic.tex').write_text(additional[0].replace('[pos=H,abovecap=4pt]', '[H]'))
    (TABLES/'appendix_diagnostics.tex').write_text(additional[3])
    sensitivity = '\n'.join(additional[1:3]).replace('[pos=H,abovecap=4pt]', '[H]')
    (TABLES/'supp_sensitivity_tables.tex').write_text(sensitivity)
    (TABLES/'additional_results.tex').write_text(
        r'\begingroup\setlength{\intextsep}{5pt}' + '\n'
        + '\n'.join(additional) + r'\endgroup' + '\n')

    analytic=read('analytic_partition.csv');body=[]
    for M in sorted(set(int(r['rows']) for r in analytic)):
        u=exactly_one([r for r in analytic if int(r['rows'])==M and r['metric']=='unit'])
        b=exactly_one([r for r in analytic if int(r['rows'])==M and r['metric']=='budget'])
        body.append(f'{M} & {sig(u["C0"])} & {sig(b["C0"])} & {count(u["iterations"])} & {count(b["iterations"])} \\\\')
    text=table(r'Exact ridge example ($\mu=0.2$, $\rho=1$).',
               'tab:analytic','rD{.}{.}{2.2}D{.}{.}{2.2}rr',r'& \multicolumn{2}{c}{Exact constant} & \multicolumn{2}{c}{Iterations}\\'+'\n'+r'\cmidrule(lr){2-3}\cmidrule(lr){4-5}'+'\n'+r'$M$ & \multicolumn{1}{c}{$C_{\rm E}$} & \multicolumn{1}{c}{$C_{\rm B}$} & Unit & Budget\\',body,placement='H',notes=r'Constants use the analytic primal and dual solutions. Iterations count steps until the absolute gap first reaches $10^{-10}$ using the squared-loss gradient at the loss proximal point. Unit and budget use the same layout.')
    (TABLES/'analytic_results.tex').write_text(text)
    write_pilot_table(read('pilot_budget_summary.csv'))
    write_continuation_table()
    print('Generated '+', '.join(p.name for p in sorted(TABLES.glob('*.tex'))))


if __name__=='__main__':
    main()
