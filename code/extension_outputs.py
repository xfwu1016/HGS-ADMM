"""Regenerate repeated-split/TCP summaries and manuscript tables from archived CSVs.

No optimization or timing is performed here. By default, derived JSON goes to
results/ and TeX to tables/. Use --summary-dir and --table-dir for an audit copy.
"""
from __future__ import annotations
import argparse
import csv
import json
from pathlib import Path
import numpy as np
from repeated_real_splits import summarize
from merge_tcp_distributed_results import validate_records

ROOT = Path(__file__).resolve().parents[1]


def read_rows(path):
    with path.open(newline='') as stream:
        return list(csv.DictReader(stream))


def mean_sd(rows, key, scale=1.):
    x = np.asarray([float(r[key])/scale for r in rows])
    return float(x.mean()), float(x.std(ddof=1))


def display(rows, key, digits, scale=1.):
    mean, sd = mean_sd(rows, key, scale)
    return f'{mean:,.{digits}f} ({sd:,.{digits}f})'


def paired_savings(rows, key):
    pairs = {}
    for row in rows:
        pairs.setdefault(int(row['seed']), {})[row['weight']] = float(row[key])
    values = {s: 100*(1-v['budget']/v['unit']) for s, v in sorted(pairs.items())}
    return {'mean': float(np.mean(list(values.values()))),
            'sd_percentage_points': float(np.std(list(values.values()), ddof=1)),
            'by_seed': values}


def editorial_template(name, generated, replacements=None):
    """Preserve the reviewed captions and scope notes; replace numerical rows."""
    template = (Path(__file__).parent/'table_templates'/f'{name}.tex.in').read_text()
    start = generated.index('\\midrule') + len('\\midrule')
    end = generated.index('\\bottomrule', start)
    text = template.replace('@@BODY@@', generated[start:end].lstrip('\n'))
    for key, value in (replacements or {}).items():
        text = text.replace(f'@@{key}@@', value)
    if '@@' in text:
        raise ValueError(f'Unfilled table template: {name}')
    return text


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--results-dir', type=Path, default=ROOT/'results')
    ap.add_argument('--summary-dir', type=Path)
    ap.add_argument('--table-dir', type=Path, default=ROOT/'tables')
    args = ap.parse_args()
    summary_dir = args.summary_dir or args.results_dir
    summary_dir.mkdir(parents=True, exist_ok=True)
    args.table_dir.mkdir(parents=True, exist_ok=True)
    real = read_rows(args.results_dir/'repeated_real_splits.csv')
    expected = {(ds, s, M, J, arm)
                for ds in ('diabetes', 'breast_cancer') for s in range(2026, 2031)
                for M, J, arm in ([(1, 1, 'unit'), (4, 1, 'unit'), (4, 1, 'budget')] +
                                 ([(4, 4, 'unit'), (4, 4, 'budget')] if ds == 'diabetes' else []))}
    if {(r['dataset'], int(r['split_seed']), int(r['M']), int(r['J']), r['weight']) for r in real} != expected:
        raise ValueError('Repeated-split CSV does not match the declared 40-arm design')
    real_summary = summarize(real)
    (summary_dir/'repeated_real_splits_summary.json').write_text(json.dumps(real_summary, indent=2, allow_nan=False)+'\n')
    tcp = validate_records(read_rows(args.results_dir/'tcp_distributed_solver.csv'))
    lan = [r for r in tcp if r['dataset']=='diabetes' and r['profile']=='lan']
    tcp_summary = {
        'design': 'Five paired Diabetes LAN splits, one timing per arm and split; one fixed-split Diabetes WAN and breast-cancer LAN pair. Unit always precedes budget in the archived command.',
        'rows': len(tcp), 'all_converged': True,
        'loop_time_paired_savings_percent': paired_savings(lan, 'worker_wall_s'),
        'payload_paired_savings_percent': paired_savings(lan, 'payload_bytes'),
        'summary_by_weight': {},
        'max_coefficient_distance_to_reference': max(float(r['coefficient_distance_to_reference']) for r in tcp),
        'max_absolute_objective_difference_to_reference': max(abs(float(r['objective_difference_to_reference'])) for r in tcp),
        'limitations': 'Single host, one timing per split and arm, fixed execution order; no within-split timing uncertainty or physical network scaling estimate.',
        'payload_scope': 'Iteration messages only, including 8-byte frame headers; excludes the 3-byte END control sentinel, setup IPC and transport headers. For this collocated 4x1 deployment: k(72p+16) bytes.'}
    for arm in ('unit', 'budget'):
        z = [r for r in lan if r['weight']==arm]
        tcp_summary['summary_by_weight'][arm] = {k: dict(zip(('mean', 'sd'), mean_sd(z, k)))
                                               for k in ('iterations', 'payload_bytes', 'messages', 'worker_wall_s')}
    (summary_dir/'tcp_distributed_solver_summary.json').write_text(json.dumps(tcp_summary, indent=2, allow_nan=False)+'\n')

    header = r'''% Generated by code/extension_outputs.py from archived CSVs.
\begin{table*}[pos=tbp]
\centering\small
\setlength{\tabcolsep}{4pt}
\renewcommand{\arraystretch}{1.12}
'''
    real_tex = header + r'''\caption{Repeated public-data splits on the sample-partitioned $4\times1$ layout. Entries are mean (standard deviation) over five paired splits. Both metrics use the same objective and relative Fenchel-gap target $10^{-7}$.}
\label{tab:repeated-real}
\begin{tabular}{llrrr}
\toprule
Dataset & Weights & Iterations & Update scalars ($10^6$) & Test metric\\
\midrule
'''
    for ds, label in [('diabetes', 'Diabetes'), ('breast_cancer', 'Breast cancer')]:
        for arm, arm_label in [('unit', 'Unit'), ('budget', 'Uniform budget')]:
            z = [r for r in real if r['dataset']==ds and int(r['M'])==4 and int(r['J'])==1 and r['weight']==arm]
            metric = ('RMSE '+display(z, 'test_rmse', 3)) if ds=='diabetes' else ('Log loss '+display(z, 'test_logloss', 5))
            real_tex += f'{label if arm=="unit" else ""} & {arm_label} & {display(z,"iterations",0)} & {display(z,"communicated_scalars",3,1e6)} & {metric}'+r'\\'+'\n'
        if ds=='diabetes': real_tex += r'\addlinespace[2pt]'+'\n'
    real_tex += r'''\bottomrule
\end{tabular}
\par\vspace{2pt}
\begin{minipage}{\linewidth}\footnotesize\raggedright Diabetes uses split-specific validation tuning of $\lambda_1$. Breast cancer uses $\lambda_1=0.001$, selected on the original validation split; later test partitions can overlap that validation set. Its predictive metrics are descriptive checks of optimizer agreement at this fixed penalty. Traffic counts the logical update ledger, excluding separate certificate traffic.\end{minipage}
\end{table*}
'''
    (args.table_dir/'table_repeated_real_splits.tex').write_text(editorial_template('table_repeated_real_splits', real_tex))

    lan_tex = header + r'''\caption{Five-split two-process TCP loopback experiment for Diabetes on the $4\times1$ layout under the LAN delay model. Entries are mean (standard deviation) over five paired splits.}
\label{tab:tcp-distributed-repeated}
\begin{tabular}{lrrrr}
\toprule
Weights & Iterations & \makecell{Application frames\\(MB)} & Messages & Loop time (s)\\
\midrule
'''
    for arm, label in [('unit', 'Unit'), ('budget', 'Uniform budget')]:
        z = [r for r in lan if r['weight']==arm]
        lan_tex += f'{label} & {display(z,"iterations",0)} & {display(z,"payload_bytes",3,1e6)} & {display(z,"messages",0)} & {display(z,"worker_wall_s",3)}'+r'\\'+'\n'
    time = tcp_summary['loop_time_paired_savings_percent']
    payload = tcp_summary['payload_paired_savings_percent']
    lan_tex += r'''\bottomrule
\end{tabular}
\par\vspace{2pt}
\begin{minipage}{\linewidth}\footnotesize\raggedright '''
    lan_tex += (f'The means of the split-level paired reductions are {payload["mean"]:.1f}\\% '
                f'(SD {payload["sd_percentage_points"]:.1f} percentage points) in payload and {time["mean"]:.1f}\\% '
                f'(SD {time["sd_percentage_points"]:.1f} percentage points) in loop time. ')
    lan_tex += r'''Each split supplies one timed run per rule, always unit before budget; these standard deviations do not estimate within-split timing variability. All runs reach relative gap $10^{-7}$. The application delay model uses 0.1 ms one-way delay and a 1 Gbps serialization parameter. Payload is decimal MB of iteration frames, excluding termination and setup messages.\end{minipage}
\end{table*}
'''
    (args.table_dir/'table_tcp_distributed_repeated.tex').write_text(editorial_template('table_tcp_distributed_repeated', lan_tex,
        {'PAYLOAD_MEAN':f'{payload["mean"]:.1f}', 'PAYLOAD_SD':f'{payload["sd_percentage_points"]:.1f}',
         'TIME_MEAN':f'{time["mean"]:.1f}', 'TIME_SD':f'{time["sd_percentage_points"]:.1f}'}))

    extra_tex = header.replace(r'\centering\small', r'\centering\scriptsize') + r'''\caption{Additional fixed-split two-process TCP execution cases. Each pair uses the same $4\times1$ layout and relative Fenchel-gap target $10^{-7}$; one run is reported per weight and dataset/profile.}
\label{tab:tcp-distributed}
\begin{tabular}{lllrrrrl}
\toprule
Dataset & Delay profile & Weights & Iterations & \makecell{Application frames\\(MB)} & Messages & Loop time (s) & Test metric\\
\midrule
'''
    for ds, profile, label, network in [('diabetes', 'wan', 'Diabetes', 'Emulated WAN'), ('breast_cancer', 'lan', 'Breast cancer', 'LAN')]:
        for arm, arm_label in [('unit', 'Unit'), ('budget', 'Uniform budget')]:
            z = next(r for r in tcp if r['dataset']==ds and r['profile']==profile and r['weight']==arm and int(r['seed'])==2026)
            metric = f'RMSE {float(z["test_rmse"]):.4f}' if ds=='diabetes' else f'Log loss {float(z["test_logloss"]):.6f}; AUC {float(z["test_auc"]):.6f}'
            extra_tex += (f'{label if arm=="unit" else ""} & {network if arm=="unit" else ""} & {arm_label} & '
                          f'{int(z["iterations"]):,} & {float(z["payload_bytes"])/1e6:.3f} & {int(z["messages"]):,} & '
                          f'{float(z["worker_wall_s"]):.3f} & {metric}'+r'\\'+'\n')
        if ds=='diabetes': extra_tex += r'\addlinespace[2pt]'+'\n'
    extra_tex += r'''\bottomrule
\end{tabular}
\par\vspace{2pt}
\begin{minipage}{\linewidth}\footnotesize\raggedright The WAN delay model uses 5 ms one-way application delay and a 20 Mbps serialization parameter; the LAN model uses 0.1 ms and 1 Gbps. These seed-2026 cases are single paired illustrations, with unit executed before budget. Both use loopback on one host; time excludes process startup and preprocessing. Payload counts iteration frames only.\end{minipage}
\end{table*}
'''
    (args.table_dir/'table_tcp_distributed.tex').write_text(editorial_template('table_tcp_distributed', extra_tex))
    print(f'Validated {len(real)} repeated-split and {len(tcp)} TCP records; generated three tables and two summaries.')


if __name__ == '__main__':
    main()
