"""Compare checkpoint residuals and bracket original-objective first hits on 16 data blocks."""
import gzip
import json
from itertools import product
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
TABLES = ROOT / "tables"
TARGET = 1e-6
MODELS = {"fused": "Squared fused", "huber": "Huber", "logistic": "Logistic"}
LAYOUTS = [(2, 8), (4, 4), (8, 2)]


def summarize_arm(history, arm, reference):
    trace = pd.DataFrame(history)
    k = trace.iteration.to_numpy()
    primal = trace.objective.to_numpy()
    step2 = trace.squared_step.to_numpy()
    expected_steps = [1, *range(10, arm.iterations + 1, 10)]
    if list(k) != expected_steps or k[-1] != arm.iterations:
        raise ValueError(f"Missing stopping checkpoint for {arm.key}")
    if trace.relative_gap.iloc[-1] > TARGET or trace.relative_gap.iloc[:-1].le(TARGET).any():
        raise ValueError(f"Inconsistent anchor first hit for {arm.key}")
    denominator = np.maximum(1.0, np.abs(primal))
    upper = reference["reference_objective"]
    lower = upper - reference["reference_gap"]
    if lower > upper or np.any(primal < lower - 1e-12 * denominator):
        raise ValueError(f"Inconsistent reference primal/dual bounds for {arm.key}")
    if not np.isfinite(primal).all() or not np.isfinite(step2).all() or np.any(step2 < 0) or not arm.c0 > 0:
        raise ValueError(f"Invalid recorded objective, squared step or constant for {arm.key}")
    low_error = np.maximum(0, primal - upper) / denominator
    high_error = (primal - lower) / denominator
    possible = k[low_error <= TARGET]
    proved = k[high_error <= TARGET]
    first_possible = int(possible[0]) if len(possible) else None
    first_proved = int(proved[0]) if len(proved) else None
    if first_possible is None or first_proved != first_possible:
        raise ValueError(f"Reference bounds do not determine the first primal hit for {arm.key}")
    ratio = k * step2 / arm.c0
    peak = int(np.argmax(ratio))
    return dict(case=arm.case, model=arm.case.split("_")[1], metric=arm.metric,
                row_parts=arm.row_parts, column_parts=arm.column_parts, target=TARGET,
                c0_reference=arm.c0, reference_primal=upper, reference_dual=lower,
                first_primal_possible=first_possible, first_primal_proved=first_proved,
                first_anchor_hit=arm.iterations, checkpoints=len(k),
                peak_ratio=float(ratio[peak]), peak_checkpoint=int(k[peak]),
                final_ratio=float(ratio[-1]))


def collect():
    layouts = pd.read_csv(RESULTS / "layout_choice_fixed16.csv")
    layouts["key"] = (layouts.case + "_M" + layouts.row_parts.astype(str)
                      + "_N" + layouts.column_parts.astype(str) + "_" + layouts.metric)
    expected = {f"synthetic_{model}_{seed}_M{m}_N{j}_{metric}"
                for model, seed, (m, j), metric in product(MODELS, range(5), LAYOUTS, ["unit", "budget"])}
    arms = {row.key: row for row in layouts.itertuples(index=False)}
    if len(layouts) != len(expected) or set(arms) != expected:
        raise ValueError("Unexpected model, seed, layout or metric in the fixed-weight grid")
    with (RESULTS / "cases.json").open() as stream:
        reference = {r["case"]: r for r in json.load(stream)}
    rows = []
    with gzip.open(RESULTS / "pilot_budget_traces.jsonl.gz", "rt") as stream:
        for line in stream:
            run = json.loads(line)
            if run["key"] in expected:
                if run["key"] not in arms:
                    raise ValueError(f"Duplicate trace for {run['key']}")
                arm = arms.pop(run["key"])
                rows.append(summarize_arm(run["history"], arm, reference[arm.case]))
    if arms:
        raise ValueError(f"Missing traces: {sorted(arms)}")
    return pd.DataFrame(rows).sort_values(["model", "case", "metric", "row_parts"])


def rank_rows(arms):
    rows = []
    for (case, model, metric), group in arms.groupby(["case", "model", "metric"]):
        c0 = group.c0_reference.rank()
        rows.append(dict(case=case, model=model, metric=metric, layouts=len(group),
                         spearman_primal=c0.corr(group.first_primal_proved.rank()),
                         spearman_anchor=c0.corr(group.first_anchor_hit.rank())))
    return pd.DataFrame(rows)


def scientific_tex(value):
    mantissa, exponent = f"{value:.2e}".split("e")
    return rf"{mantissa}\times 10^{{{int(exponent)}}}"


def write_excerpts(arms, ranks):
    supplements = [r"""% Generated by code/fixed16_bound_audit.py.
\clearpage
\section*{Residual bounds and objective accuracy on 16 data blocks}
For each of the 90 runs with unit weights or uniform budgets, let
$\widehat C_0$ denote the distance constant evaluated at the common numerical
primal--dual reference for that sample. At each recorded checkpoint $k$ we
compute $q_k=kR_k^2/\widehat C_0$. The exact residual bound uses the
distance to an exact KKT pair. The ratios below compare the recorded
squared steps with the numerical reference version of that bound.
Each run contributes its largest recorded $q_k$ and its value at the
final checkpoint $K$. Checkpoints occur at step 1 and then every ten
steps through the first certified relative gap of $10^{-6}$.

\begin{table}[H]
\centering
\caption{Residual ratios on the three layouts with 16 data blocks.
Within each model, the summaries cover five samples, three layouts and two weights (30 runs).}
\label{tab:residual-ratios}
\begin{tabular}{@{}lrrr@{}}\toprule
& \multicolumn{2}{c}{Peak over checkpoints}
& At stopping \\
\cmidrule(lr){2-3}\cmidrule(l){4-4}
Model & Median & Largest & Median $q_K$ \\
\midrule"""]
    for model, label in MODELS.items():
        g = arms[arms.model.eq(model)]
        supplements.append(
            rf"{label} & {g.peak_ratio.median():.4f} & {g.peak_ratio.max():.4f}"
            rf" & ${scientific_tex(g.final_ratio.median())}$ \\"
        )
    supplements.append(r"""\bottomrule\end{tabular}\end{table}

To isolate the objective accuracy of the coefficient vector, write
$L$ and $U$ for the dual and primal objective values of the high-accuracy
reference fit on the same sample, so $L\leq P^\star\leq U$. At each
checkpoint, compute $P_k=\mathcal P(\beta^k)$ and
$d_k=\max(1,|P_k|)$. Weak duality brackets the relative primal
suboptimality by
\[
 \frac{\max(0,P_k-U)}{d_k}\;\leq\;
 \frac{P_k-P^\star}{d_k}\;\leq\;\frac{P_k-L}{d_k}.
\]
The first checkpoint at which the lower endpoint reaches $10^{-6}$ or
less is the earliest possible hit. The first at which the upper endpoint
does so is a confirmed hit. These checkpoints agreed on every run.
This retrospective comparison uses the separate reference solve.""")
    supplements += [r"""\begin{table}[H]
\centering
\caption{First checkpoint attaining relative primal suboptimality $10^{-6}$.
For each sample and weighting rule, Spearman correlation compares the rankings of
the three layouts by $\widehat C_0$ and by the first primal hit. The final column
gives the median of the ratios of primal to anchor-certified first hits.}
\label{tab:primal-ranks}
\begin{tabular}{@{}lrrr@{}}\toprule
& \multicolumn{2}{c}{Spearman correlation}
& Median ratio of hits \\
\cmidrule(lr){2-3}\cmidrule(l){4-4}
Model & Smallest & Largest & Primal / anchor \\
\midrule"""]
    for model, label in MODELS.items():
        a = arms[arms.model.eq(model)]
        rr = ranks[ranks.model.eq(model)].spearman_primal
        fraction = (a.first_primal_proved / a.first_anchor_hit).median()
        supplements.append(rf"{label} & ${rr.min():.2f}$ & ${rr.max():.2f}$ & {fraction:.2f} \\")
    supplements.append(r"""\bottomrule\end{tabular}\end{table}""")
    (TABLES / "supp_fixed16_bound_audit.tex").write_text("\n".join(supplements) + "\n")
    smooth = ranks[ranks.model.isin(["huber", "logistic"])]
    negative = ranks[ranks.model.eq("fused")].spearman_primal.lt(0).sum()
    perfect = np.isclose(smooth.spearman_primal, 1).sum()
    inline = (
        "% Generated by code/fixed16_bound_audit.py.\n"
        rf"Across the {len(arms)} fixed-weight runs on the 16-block layouts, the largest "
        rf"recorded value of $kR_k^2/\widehat C_0$ was {arms.peak_ratio.max():.3f}, "
        r"where $\widehat C_0$ uses the numerical reference solution. "
        rf"Even at the largest ratio, $\widehat C_0/k$ was about "
        rf"{1 / arms.peak_ratio.max():.1f} times the recorded squared residual. "
        r"The primal and dual reference values also identified the first checkpoint "
        r"attaining $10^{-6}$ relative primal suboptimality in every run. "
        rf"With this endpoint, the within-rule layout ranks agreed with the $C_0$ ranks "
        rf"in {perfect} of {len(smooth)} Huber and logistic comparisons. The correlations "
        rf"were negative in {negative} of {len(ranks)-len(smooth)} fused comparisons "
        r"(Supplementary Tables~\ref{supp-tab:residual-ratios}--\ref{supp-tab:primal-ranks})." + "\n"
    )
    (TABLES / "experiment_residual_validation.tex").write_text(inline)


def main():
    arms = collect()
    ranks = rank_rows(arms)
    arms.to_csv(RESULTS / "fixed16_bound_audit.csv", index=False)
    ranks.to_csv(RESULTS / "fixed16_bound_ranks.csv", index=False)
    write_excerpts(arms, ranks)
    print(f"Bracketed {len(arms)} first hits and summarized {len(ranks)} within-rule comparisons.")


if __name__ == "__main__":
    main()
