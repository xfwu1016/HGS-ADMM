"""Rebuild rank diagnostics and descriptively stratified paired traffic comparisons."""
from __future__ import annotations

import argparse
from itertools import combinations
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
COST = "payload_with_certificate_bound"
MEASURES = ["distance_constant_approx", "iterations"]
KEYS = ["data", "model", "seed", "row_parts", "column_parts"]
NAMES = {
    "fused": "Squared fused", "huber": "Huber", "logistic": "Logistic",
    "diabetes": "Diabetes", "breast_cancer": "Breast cancer",
}


def rank_diagnostics(results, tables):
    runs = pd.read_csv(results / "runs.csv")
    # The extra two padded runs implement a different graph on the same data.
    main = runs.loc[runs.zero_edges.eq(0)].copy()
    main["model"] = main.case.str.replace(r"^synthetic_|^real_|_\d+$", "", regex=True)
    if main.duplicated(["case", "row_parts", "column_parts", "metric"]).any():
        raise ValueError("Ambiguous layout/metric combination in the primary experiment.")
    if not main.groupby("case").size().eq(8).all():
        raise ValueError("Each case needs both metrics on four primary layouts.")
    cases, ranked = [], []
    for case, group in main.groupby("case"):
        rank = group[MEASURES].rank(method="average")
        ranked.append(rank)
        products = [np.prod(right - left) for left, right in combinations(rank.to_numpy(), 2)]
        cases.append(dict(case=case, model=group.model.iloc[0], runs=len(group),
                          spearman=rank.corr().iloc[0, 1],
                          concordant=sum(x > 0 for x in products),
                          discordant=sum(x < 0 for x in products),
                          tied_on_either_measure=sum(x == 0 for x in products)))
    cases = pd.DataFrame(cases)
    cases.to_csv(results / "rank_diagnostics_cases.csv", index=False)
    summary = pd.DataFrame([dict(
        runs=len(main), cases=len(cases), raw_pooled_spearman=main[MEASURES].corr(method="spearman").iloc[0, 1],
        correlation_of_concatenated_within_case_ranks=pd.concat(ranked).corr().iloc[0, 1],
        median_case_spearman=cases.spearman.median(),
        concordant=cases.concordant.sum(), discordant=cases.discordant.sum(),
        tied_on_either_measure=cases.tied_on_either_measure.sum(),
    )])
    summary.to_csv(results / "rank_diagnostics_overall.csv", index=False)
    groups = main.loc[main.kind.eq("synthetic") & main.column_parts.eq(4)]
    means = groups.groupby(["model", "row_parts", "metric"])[MEASURES].mean().unstack("metric")
    contrasts = pd.DataFrame({
        field + "_budget_minus_unit": means[(field, "budget")] - means[(field, "unit")]
        for field in MEASURES
    })
    differences = contrasts.prod(axis=1)
    contrasts["ordering"] = np.select([differences.gt(0), differences.lt(0)], ["agrees", "disagrees"], default="tie")
    contrasts.to_csv(results / "rank_diagnostics_metric_contrasts.csv")

    def fmt(value):
        return f"${value:.2f}$" if abs(value) >= 0.005 else r"$0.00$"

    table = [
        "% Generated by code/referee_diagnostics.py.",
        r"\begin{table}[pos=tbp]", r"\centering\small",
        r"\caption{Within-sample rank correlation between the initial-distance constant and iterations to relative gap $10^{-6}$ (simulations) or $10^{-7}$ (public data) using projected anchor multipliers.}",
        r"\label{tab:rank-diagnostics}",
        r"\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}lrrr@{}}", r"\toprule",
        r"Model or dataset & Samples & Median & Range\\", r"\midrule",
    ]
    for model, name in NAMES.items():
        values = cases.loc[cases.model.eq(model), "spearman"]
        if values.empty:
            raise ValueError(f"Missing data for {model}.")
        limits = (fmt(values.min()) + "--" + fmt(values.max())) if len(values) > 1 else "---"
        table.append(f"{name} & {len(values)} & {fmt(values.median())} & {limits}" + r"\\")
    table += [r"\bottomrule", r"\end{tabular*}", r"\end{table}"]
    (tables / "rank_diagnostics.tex").write_text("\n".join(table) + "\n", encoding="utf-8")


def payload_diagnostics(results, tables):
    continuation = pd.concat([pd.read_csv(results / name) for name in
                              ["pilot_continuation_runs.csv", "pilot_continuation_public.csv"]])
    fixed = continuation.loc[continuation.requested_prefix_iterations.eq(100)].pivot(
        index=KEYS, columns="method", values=COST)
    control = pd.read_csv(results / "matched_output_control.csv").rename(columns={
        "sample_blocks": "row_parts", "feature_blocks": "column_parts"}).set_index(KEYS)
    matched = fixed.join(control[["uniform_scalars", "learned_scalars"]], validate="one_to_one")
    if matched.isna().any().any() or not matched.unit_continue.eq(matched.learned_scalars).all():
        raise ValueError("Matched checkpoint records disagree with continuation records.")
    matched["lower_fixed"] = matched[["unit", "budget"]].min(axis=1)
    comparisons = []

    def add(values, method, reference, basis="including certificate bound"):
        frame = values[[method, reference]].reset_index()
        frame = frame.rename(columns={method: "method_scalars", reference: "reference_scalars"})
        frame["method"], frame["reference"], frame["accounting"] = method, reference, basis
        comparisons.append(frame)

    for reference in ["unit_restart", "uniform_scalars", "unit", "budget", "lower_fixed"]:
        add(matched, "unit_continue", reference)
    add(matched, "budget_continue", "budget")

    pilot = pd.read_csv(results / "pilot_budget_runs.csv")
    pilot["data"] = "synthetic"
    pilot["model"] = pilot.case.str.replace(r"^synthetic_|_\d+$", "", regex=True)
    pilot["including_checks"] = pilot.total_optimization_allocation_payload + pilot.certificate_payload_bound
    for field, basis in [("total_optimization_allocation_payload", "optimization and allocation"),
                         ("including_checks", "including certificate bound")]:
        values = pilot.pivot(index=KEYS, columns="metric", values=field)
        add(values, "pilot", "budget", basis)

    pairs = pd.concat(comparisons, ignore_index=True)
    pairs["change_pct"] = 100 * (pairs.method_scalars / pairs.reference_scalars - 1)

    def summarize(group):
        changes = group.change_pct
        return pd.Series(dict(
            pairs=len(group), lower_count=sum(changes < 0), equal_count=sum(changes == 0),
            median_paired_change_pct=changes.median(), min_paired_change_pct=changes.min(),
            max_paired_change_pct=changes.max(),
            change_in_mean_scalars_pct=100 * (group.method_scalars.mean() / group.reference_scalars.mean() - 1),
        ))

    group = ["data", "method", "reference", "accounting"]
    summary_tables = {}
    for filename, columns in [("paired_payload_strata", group + ["model", "row_parts", "column_parts"]),
                              ("paired_payload_overall", group)]:
        table = pairs.groupby(columns).apply(summarize, include_groups=False).reset_index()
        table[["pairs", "lower_count", "equal_count"]] = table[["pairs", "lower_count", "equal_count"]].astype(int)
        table.to_csv(results / (filename + ".csv"), index=False)
        summary_tables[filename] = table
    write_paired_table(tables, summary_tables["paired_payload_strata"], summary_tables["paired_payload_overall"])




def write_paired_table(tables, strata, overall):
    rows = strata.loc[strata.accounting.eq("including certificate bound")].pivot(
        index=["model", "row_parts", "column_parts"],
        columns=["method", "reference"], values="median_paired_change_pct")
    columns = [("unit_continue", "unit_restart"), ("unit_continue", "uniform_scalars"),
               ("unit_continue", "lower_fixed"), ("budget_continue", "budget")]
    table = [
        "% Generated by code/referee_diagnostics.py.",
        r"\begin{table*}", r"\centering\small",
        r"\caption{Median paired changes in charged communication (\%) by model and layout.}",
        r"\label{tab:paired-strata}", r"\begin{tabular}{@{}lcrrrr@{}}", r"\toprule",
        r" & & \multicolumn{3}{c}{Unit-weight pilot} & Uniform-budget pilot\\",
        r"\cmidrule(lr){3-5}\cmidrule(l){6-6}",
        r"Model & Layout & Restart & Switch to uniform & Lower-cost fixed & Keep uniform\\",
        r"\midrule",
    ]
    for model, name in NAMES.items():
        for i, ((m, j), values) in enumerate(rows.loc[model].iterrows()):
            terms = [name if i == 0 else "", rf"${m}\times{j}$"]
            terms.extend(f"${values[column]:+.2f}$" for column in columns)
            table.append(" & ".join(terms) + r"\\")
        table.append(r"\addlinespace[2pt]")
    table[-1] = r"\midrule"
    pooled = overall[overall.accounting.eq("including certificate bound")].set_index(["data", "method", "reference"])
    uniform_prefix_counts = []
    for kind, label in [("synthetic", "All simulations"), ("real", "Public examples")]:
        cells = [label, "---"]
        for method, reference in columns:
            value = pooled.loc[(kind, method, reference)]
            cells.append(f"${value.median_paired_change_pct:+.2f}$")
        table.append(" & ".join(cells) + r"\\")
        uniform_prefix_counts.append(f"{int(value.lower_count)}/{int(value.pairs)}")
    table += [
        r"\bottomrule", r"\end{tabular}", r"\par\vspace{3pt}",
        r"\begin{minipage}{0.85\linewidth}\footnotesize\raggedright",
        r"Projected anchor multipliers certify relative gaps of $10^{-6}$ (simulations) and $10^{-7}$ "
        "(public data). Each entry uses paired scalar counts from five simulated samples or one public "
        "split. The first three comparisons start with unit weights. The last starts both methods "
        "with uniform budgets and compares learned with unchanged output weights. "
        r"Changes equal $100(C_{\rm continue}/C_{\rm comparison}-1)$ and negative values favor "
        r"continuation, or retaining the state when both arms learn the same weights. "
        r"Positive differences below 0.005\% appear as $+0.00$. "
        "The last two rows pool the paired differences. For the uniform-budget "
        f"pilot, the learned continuation uses less traffic in {uniform_prefix_counts[0]} simulated "
        f"and {uniform_prefix_counts[1]} public-data comparisons. "
        "The accounting includes the upper bound for certificate messages.",
        r"\end{minipage}", r"\end{table*}",
    ]
    (tables / "paired_strata.tex").write_text("\n".join(table) + "\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT,
                        help="Reproducibility folder containing results/ and tables/.")
    root = parser.parse_args().root
    rank_diagnostics(root / "results", root / "tables")
    payload_diagnostics(root / "results", root / "tables")


if __name__ == "__main__":
    main()
