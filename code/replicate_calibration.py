"""Calibrate an absolute optimization gap against repeated-response variability."""
from __future__ import annotations

import csv
from pathlib import Path

import numpy as np

from hybrid_solver import GraphSplitting, make_regression
from run_experiments import synthetic_case

ROOT = Path(__file__).resolve().parents[1]
LAYOUTS = ((2, 8), (4, 4), (8, 2))
PILOT_STEPS = 200
FRACTION = 0.25
MAX_STEPS = 20_000


def checkpoints(design, response, settings, layout, metric, cap):
    solver = GraphSplitting(make_regression(design, response, *layout, **settings),
                            weights=metric)
    for step in range(1, cap + 1):
        local = solver.prox(solver.eta - solver.u)
        solver.eta = solver.project(local)
        solver.u += local - solver.eta
        if step == 1 or step % 10 == 0 or step == cap:
            primal, _, gap = solver.certificate()
            beta = np.concatenate([solver.eta[block] for block in solver.xs])
            yield step, primal, gap, beta


def write_csv(path, rows):
    with path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def main():
    summaries, runs = [], []
    for seed in range(5):
        case = synthetic_case("fused", seed)
        X, y, truth, settings = (case[name] for name in ("X", "y", "truth", "args"))
        rng = np.random.default_rng(202_696_000 + seed)
        repeated_y = X @ truth + rng.standard_normal(X.shape[0])
        prediction = X / np.sqrt(X.shape[0])
        pilots = [
            next(record for record in checkpoints(X, response, settings, (4, 4), "unit",
                                                  PILOT_STEPS) if record[0] == PILOT_STEPS)
            for response in (y, repeated_y)
        ]
        _, _, gap_1, beta_1 = pilots[0]
        _, _, gap_2, beta_2 = pilots[1]
        separation = np.linalg.norm(prediction @ (beta_1 - beta_2))
        lower = max(0.0, separation - np.sqrt(2 * gap_1) - np.sqrt(2 * gap_2))
        tolerance = (FRACTION * lower) ** 2 / 2
        seed_runs = []
        for layout in LAYOUTS:
            for metric in ("unit", "budget"):
                calibrated, strict = None, None
                for step, primal, gap, _ in checkpoints(X, y, settings, layout, metric, MAX_STEPS):
                    if lower > 0 and calibrated is None and gap <= tolerance:
                        calibrated = step, gap
                    if strict is None and gap / max(1.0, abs(primal)) <= 1e-6:
                        strict = step, gap
                    if strict is not None and (lower == 0 or calibrated is not None):
                        break
                else:
                    raise RuntimeError(f"Endpoint not reached: {seed}, {layout}, {metric}")
                early_step, early_gap = calibrated if calibrated is not None else (None, None)
                row = dict(seed=seed, row_parts=layout[0], column_parts=layout[1],
                           metric=metric, calibrated_step=early_step, calibrated_gap=early_gap,
                           strict_step=strict[0], strict_gap=strict[1])
                runs.append(row)
                seed_runs.append(row)
        ratios = [r["calibrated_step"] / r["strict_step"] for r in seed_runs
                  if r["calibrated_step"] is not None]
        summaries.append(dict(seed=seed, pilot_gap_1=gap_1, pilot_gap_2=gap_2,
                              pilot_separation=separation, separation_lower_bound=lower,
                              absolute_target=tolerance, fits_with_target=len(ratios),
                              median_step_ratio=float(np.median(ratios)) if ratios else ""))
    results = ROOT / "results"
    results.mkdir(exist_ok=True)
    write_csv(results / "replicate_calibration.csv", summaries)
    write_csv(results / "replicate_calibration_runs.csv", runs)
    lines = []
    for row in summaries:
        ratio = row["median_step_ratio"]
        ratio_tex = f"{ratio:.2f}" if ratio != "" else "--"
        mantissa, exponent = f'{row["absolute_target"]:.2e}'.split("e")
        tolerance_tex = (
            "0" if row["absolute_target"] == 0 else
            rf"${mantissa}\times10^{{{int(exponent)}}}$"
        )
        lines.append(
            f'{row["seed"] + 1} & {row["pilot_separation"]:.3f} & '
            f'{row["separation_lower_bound"]:.3f} & '
            f'{tolerance_tex} & {ratio_tex} ' + r"\\")
    (ROOT / "tables").mkdir(exist_ok=True)
    (ROOT / "tables" / "replicate_calibration_rows.tex").write_text(
        r"% Generated by code/replicate_calibration.py." + "\n"
        + r"\newcommand{\replicatecalibrationrows}{%" + "\n"
        + "\n".join(lines) + "\n}\n",
        encoding="utf-8")
    for row in summaries:
        print(row)


if __name__ == "__main__":
    main()
